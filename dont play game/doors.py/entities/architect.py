import random
from entities.base_entity import BaseEntity

class Architect(BaseEntity):
    def __init__(self):
        super().__init__(name="Водный Свет (Архитектор)", spawn_chance=1.0)

    def can_spawn(self, room) -> bool:
        # Архитектор — это не обычный монстр, он не спавнится в комнатах как враг
        return False

    def trigger(self, player, room) -> bool:
        return True

    def give_death_message(self, death_count: int, cause_of_death: str):
        """Вызывается при смерти игрока и реагирует в зависимости от количества смертей."""
        print("\n" + "✨" * 30)
        print("💧 [ВОДНЫЙ СВЕТ / АРХИТЕКТОР появился в темноте] 💧")
        print("✨" * 30)

        # 1. Если смертей больше 100 — Архитектор в полной модераторской депрессии
        if death_count >= 100:
            messages = [
                "Пожалуйста... хватит умирать. Я устал пересоздавать эти стены...",
                "Серьёзно? 100+ смертей? Я уже путаю, где тут дверь 35, а где 90...",
                "Я Архитектор этого места, а не твой сиделка! Хватит падать в лужи!",
                "Мои границы терпения официально вышли из строя. Перестань врезаться в монстров!"
            ]
            print(f"🌊 Водный Свет: «{random.choice(messages)}»")

        # 2. Если смертей от 20 до 99 — начинает путать подсказки и названия
        elif death_count >= 20:
            confused_names = ["Драш... или это был Драш-Раш?", "Нубинька... а, нет, Фигурка... или Нубини?", "Сик... или Чёрный Бегун?"]
            print(f"🌀 Водный Свет (путая названия): «Тебя убил... э-э-э... {random.choice(confused_names)}. Короче, прямо не беги и не шуми!»")
            print("💧 Водный Свет: «Я предупреждал тебя, но в моих чертежах уже всё путается...»")

        # 3. Обычная поддержка (от 1 до 19 смертей) — классический путеводный свет
        else:
            print(f"💡 Водный Свет: «Причина твоей гибели: {cause_of_death}.»")
            print("💡 Водный Свет: «Запомни алгоритм этой комнаты и пробуй снова, я подсвечу тебе путь!»")

        print("✨" * 30 + "\n")


def setup():
    return Architect()